import { act, fireEvent, render, screen, waitFor, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { describe, expect, it, vi } from 'vitest'
import { ApiError } from '@/api/errors'
import type { PaperSettings as Settings } from '@/api/paper'
import { createWorkspaceApi, type WorkspaceApi } from '@/api/workspace'
import { PaperSettings } from './PaperSettings'

type Api = Pick<WorkspaceApi, 'paperSettings' | 'savePaperSettings'>
const defaults: Settings = { enabled: false, checkIntervalMinutes: 60 }
const makeApi = (settings = defaults) => ({
  paperSettings: vi.fn<WorkspaceApi['paperSettings']>().mockResolvedValue(settings),
  savePaperSettings: vi.fn<WorkspaceApi['savePaperSettings']>().mockImplementation(async settings => settings),
})
function deferred<T>() {
  let resolve!: (value: T) => void
  let reject!: (reason: unknown) => void
  const promise = new Promise<T>((yes, no) => { resolve = yes; reject = no })
  return { promise, resolve, reject }
}

describe('PaperSettings', () => {
  it('shows safe disabled/60 defaults while loading and aborts the read on unmount', async () => {
    const pending = deferred<Settings>()
    const api = makeApi()
    api.paperSettings.mockReturnValue(pending.promise)
    const onChange = vi.fn()
    const view = render(<PaperSettings api={api} onChange={onChange} />)
    expect(screen.getByRole('switch', { name: 'Enable paper trading' })).not.toBeChecked()
    expect(screen.getByRole('switch')).toBeDisabled()
    expect(screen.getByRole('spinbutton')).toHaveValue(60)
    expect(screen.getByRole('spinbutton')).toBeDisabled()
    expect(screen.getByRole('button', { name: 'Save paper settings' })).toBeDisabled()
    expect(screen.getByText(/independent of the real-account monitor/)).toBeInTheDocument()
    const signal = api.paperSettings.mock.calls[0]?.[0]
    view.unmount()
    expect(signal?.aborted).toBe(true)
    await act(async () => pending.resolve({ enabled: true, checkIntervalMinutes: 1 }))
    expect(onChange).not.toHaveBeenCalled()
    expect(api.savePaperSettings).not.toHaveBeenCalled()
  })

  it('edits the interval even while disabled, saves only on submit and reports confirmed settings', async () => {
    const user = userEvent.setup()
    const api = makeApi()
    const onChange = vi.fn()
    render(<PaperSettings api={api} onChange={onChange} />)
    await waitFor(() => expect(screen.getByRole('spinbutton')).toBeEnabled())
    expect(onChange).toHaveBeenCalledExactlyOnceWith(defaults)
    fireEvent.change(screen.getByRole('spinbutton'), { target: { value: '15' } })
    expect(api.savePaperSettings).not.toHaveBeenCalled()
    expect(onChange).toHaveBeenCalledTimes(1)
    await user.click(screen.getByRole('switch'))
    await user.click(screen.getByRole('button', { name: 'Save paper settings' }))
    expect(api.savePaperSettings).toHaveBeenCalledExactlyOnceWith({ enabled: true, checkIntervalMinutes: 15 })
    expect(await screen.findByText('Paper settings saved.')).toBeInTheDocument()
    expect(onChange).toHaveBeenLastCalledWith({ enabled: true, checkIntervalMinutes: 15 })
    expect(screen.getByRole('button', { name: 'Save paper settings' })).toBeDisabled()
  })

  it('rejects missing, fractional and out-of-range intervals and accepts both bounds', async () => {
    const api = makeApi()
    render(<PaperSettings api={api} />)
    await waitFor(() => expect(screen.getByRole('spinbutton')).toBeEnabled())
    for (const value of ['', '0', '-1', '1.5', '1441']) {
      fireEvent.change(screen.getByRole('spinbutton'), { target: { value } })
      expect(screen.getByRole('spinbutton')).toHaveAttribute('aria-invalid', 'true')
      expect(screen.getByRole('button', { name: 'Save paper settings' })).toBeDisabled()
      fireEvent.submit(screen.getByRole('button', { name: 'Save paper settings' }).closest('form')!)
    }
    expect(api.savePaperSettings).not.toHaveBeenCalled()
    for (const value of ['1', '1440']) {
      fireEvent.change(screen.getByRole('spinbutton'), { target: { value } })
      expect(screen.getByRole('spinbutton')).toHaveAttribute('aria-invalid', 'false')
      expect(screen.getByRole('button', { name: 'Save paper settings' })).toBeEnabled()
    }
  })

  it('fails closed on a failed or malformed read and recovers only with an explicit reload', async () => {
    const api = makeApi()
    api.paperSettings.mockRejectedValueOnce(new Error('Private transport detail'))
      .mockResolvedValueOnce({ enabled: 'yes', checkIntervalMinutes: 60 } as unknown as Settings)
      .mockResolvedValue(defaults)
    const onChange = vi.fn()
    render(<PaperSettings api={api} onChange={onChange} />)
    expect(await screen.findByRole('alert')).toHaveTextContent('Paper settings could not be loaded. No changes have been made.')
    expect(screen.queryByText('Private transport detail')).not.toBeInTheDocument()
    expect(screen.getByRole('switch')).toBeDisabled()
    expect(onChange).not.toHaveBeenCalled()
    await userEvent.click(screen.getByRole('button', { name: 'Reload paper settings' }))
    expect(await screen.findByRole('alert')).toHaveTextContent('Paper settings could not be loaded.')
    expect(screen.getByRole('switch')).toBeDisabled()
    await userEvent.click(screen.getByRole('button', { name: 'Reload paper settings' }))
    await waitFor(() => expect(screen.getByRole('switch')).toBeEnabled())
    expect(onChange).toHaveBeenCalledExactlyOnceWith(defaults)
    expect(api.paperSettings).toHaveBeenCalledTimes(3)
  })

  it('handles older API fixtures without paper settings methods safely', async () => {
    const view = render(<PaperSettings api={{} as Api} />)
    expect(await screen.findByRole('alert')).toHaveTextContent('Paper settings could not be loaded.')
    expect(screen.getByRole('switch')).toBeDisabled()
    const onChange = vi.fn()
    view.rerender(<PaperSettings api={{ paperSettings: vi.fn().mockResolvedValue(defaults) } as unknown as Api} onChange={onChange} />)
    await waitFor(() => expect(screen.getByRole('switch')).toBeEnabled())
    await userEvent.click(screen.getByRole('switch'))
    await userEvent.click(screen.getByRole('button', { name: 'Save paper settings' }))
    expect(await screen.findByRole('alert')).toHaveTextContent('Paper settings could not be saved.')
    expect(onChange).toHaveBeenCalledExactlyOnceWith(defaults)
  })

  it('does not treat a malformed save response as confirmed settings', async () => {
    const api = makeApi()
    api.savePaperSettings.mockResolvedValue({ enabled: true, checkIntervalMinutes: 0 })
    const onChange = vi.fn()
    render(<PaperSettings api={api} onChange={onChange} />)
    await waitFor(() => expect(screen.getByRole('switch')).toBeEnabled())
    await userEvent.click(screen.getByRole('switch'))
    await userEvent.click(screen.getByRole('button', { name: 'Save paper settings' }))
    expect(await screen.findByRole('alert')).toHaveTextContent('Paper settings could not be saved.')
    expect(onChange).toHaveBeenCalledExactlyOnceWith(defaults)
    expect(screen.queryByText('Paper settings saved.')).not.toBeInTheDocument()
  })

  it('allows only one save at a time and does not publish an unconfirmed save', async () => {
    const pending = deferred<Settings>()
    const api = makeApi()
    api.savePaperSettings.mockReturnValue(pending.promise)
    const onChange = vi.fn()
    render(<PaperSettings api={api} onChange={onChange} />)
    await waitFor(() => expect(screen.getByRole('switch')).toBeEnabled())
    await userEvent.click(screen.getByRole('switch'))
    const button = screen.getByRole('button', { name: 'Save paper settings' })
    fireEvent.submit(button.closest('form')!)
    fireEvent.submit(button.closest('form')!)
    expect(api.savePaperSettings).toHaveBeenCalledTimes(1)
    expect(button).toBeDisabled()
    expect(screen.getByRole('switch')).toBeDisabled()
    expect(onChange).toHaveBeenCalledTimes(1)
    await act(async () => pending.reject(new ApiError('http', 'Paper checks are unavailable.', 503)))
    expect(screen.getByRole('alert')).toHaveTextContent('Paper checks are unavailable.')
    expect(screen.queryByText('Paper settings saved.')).not.toBeInTheDocument()
    expect(onChange).toHaveBeenCalledTimes(1)
    expect(button).toBeEnabled()
  })

  it('ignores stale reads when the API changes, including a switch back to the same API object', async () => {
    const firstRead = deferred<Settings>()
    const nextRead = deferred<Settings>()
    const first = makeApi()
    first.paperSettings.mockReturnValueOnce(firstRead.promise).mockReturnValueOnce(nextRead.promise)
    const second = makeApi({ enabled: true, checkIntervalMinutes: 2 })
    const onChange = vi.fn()
    const view = render(<PaperSettings api={first} onChange={onChange} />)
    const oldSignal = first.paperSettings.mock.calls[0]?.[0]
    view.rerender(<PaperSettings api={second} onChange={onChange} />)
    await waitFor(() => expect(screen.getByRole('spinbutton')).toHaveValue(2))
    expect(oldSignal?.aborted).toBe(true)
    view.rerender(<PaperSettings api={first} onChange={onChange} />)
    await act(async () => firstRead.resolve({ enabled: true, checkIntervalMinutes: 1440 }))
    expect(screen.getByRole('switch')).toBeDisabled()
    expect(onChange).toHaveBeenCalledTimes(1)
    await act(async () => nextRead.resolve(defaults))
    expect(screen.getByRole('spinbutton')).toHaveValue(60)
    expect(onChange).toHaveBeenLastCalledWith(defaults)
  })

  it('does not restore old confirmed settings on an API round trip before the fresh read completes', async () => {
    const pendingOther = deferred<Settings>()
    const pendingAgain = deferred<Settings>()
    const first = makeApi()
    first.paperSettings.mockResolvedValueOnce(defaults).mockReturnValueOnce(pendingAgain.promise)
    const second = makeApi()
    second.paperSettings.mockReturnValue(pendingOther.promise)
    const onChange = vi.fn()
    const view = render(<PaperSettings api={first} onChange={onChange} />)
    await waitFor(() => expect(screen.getByRole('switch')).toBeEnabled())
    view.rerender(<PaperSettings api={second} onChange={onChange} />)
    view.rerender(<PaperSettings api={first} onChange={onChange} />)
    expect(screen.getByRole('switch')).toBeDisabled()
    await act(async () => pendingOther.reject(new Error('Late private error')))
    expect(screen.queryByRole('alert')).not.toBeInTheDocument()
    expect(onChange).toHaveBeenCalledTimes(1)
    await act(async () => pendingAgain.resolve({ enabled: true, checkIntervalMinutes: 10 }))
    expect(screen.getByRole('switch')).toBeChecked()
    expect(screen.getByRole('spinbutton')).toHaveValue(10)
    expect(onChange).toHaveBeenCalledTimes(2)
  })

  it.each(['replace', 'unmount'] as const)('ignores a late save after %s, without calling the current callback', async action => {
    const pending = deferred<Settings>()
    const first = makeApi()
    first.savePaperSettings.mockReturnValue(pending.promise)
    const onChange = vi.fn()
    const view = render(<PaperSettings api={first} onChange={onChange} />)
    await waitFor(() => expect(screen.getByRole('switch')).toBeEnabled())
    await userEvent.click(screen.getByRole('switch'))
    await userEvent.click(screen.getByRole('button', { name: 'Save paper settings' }))
    const second = makeApi({ enabled: false, checkIntervalMinutes: 5 })
    if (action === 'replace') {
      view.rerender(<PaperSettings api={second} onChange={onChange} />)
      await waitFor(() => expect(screen.getByRole('spinbutton')).toHaveValue(5))
    } else view.unmount()
    const changes = onChange.mock.calls.length
    await act(async () => pending.resolve({ enabled: true, checkIntervalMinutes: 60 }))
    expect(onChange).toHaveBeenCalledTimes(changes)
    if (action === 'replace') {
      expect(screen.getByRole('spinbutton')).toHaveValue(5)
      expect(screen.getByRole('switch')).not.toBeChecked()
      expect(screen.queryByText('Paper settings saved.')).not.toBeInTheDocument()
    }
  })

  it('uses the newest callback without rereading or overwriting unsaved edits', async () => {
    const api: Api = makeApi()
    const first = vi.fn()
    const second = vi.fn()
    const view = render(<PaperSettings api={api} onChange={first} />)
    await waitFor(() => expect(first).toHaveBeenCalledOnce())
    await userEvent.click(screen.getByRole('switch'))
    view.rerender(<PaperSettings api={api} onChange={second} />)
    expect(screen.getByRole('switch')).toBeChecked()
    await userEvent.click(screen.getByRole('button', { name: 'Save paper settings' }))
    await waitFor(() => expect(second).toHaveBeenCalledExactlyOnceWith({ ...defaults, enabled: true }))
    expect(first).toHaveBeenCalledTimes(1)
    expect(api.paperSettings).toHaveBeenCalledTimes(1)
  })

  it('requires confirmation before disabling saved enabled settings, and cancel makes no write', async () => {
    const api = makeApi({ ...defaults, enabled: true })
    const onChange = vi.fn()
    render(<PaperSettings api={api} onChange={onChange} />)
    await waitFor(() => expect(screen.getByRole('switch')).toBeEnabled())
    await userEvent.click(screen.getByRole('switch'))
    await userEvent.click(screen.getByRole('button', { name: 'Save paper settings' }))
    const dialog = await screen.findByRole('dialog', { name: 'Disable paper monitoring?' })
    expect(dialog).toHaveTextContent('Monitoring will stop for all armed and open paper Plays.')
    expect(dialog).toHaveTextContent('Existing capital reservations remain held while open exposure is unknown.')
    expect(dialog).toHaveTextContent('Price touches while disabled are not retroactively simulated')
    expect(dialog).toHaveTextContent('Re-enabling resumes suspended Plays prospectively at a fresh minute boundary')
    expect(dialog).toHaveTextContent('owner-paused Plays stay paused')
    expect(dialog).toHaveTextContent('Unevaluated history remains unscored after resumption')
    expect(dialog).toHaveTextContent('Unevaluated time before disabling is also skipped and remains unscored.')
    expect(dialog).toHaveTextContent('Any position open at suspension keeps new entries on that account blocked after re-enabling until that exposure closes.')
    expect(dialog).toHaveTextContent('Entries touched during the hold are declined, not replayed.')
    expect(dialog).toHaveTextContent('Paper history stays available.')
    expect(dialog).not.toHaveTextContent('Candle history gap')
    expect(api.savePaperSettings).not.toHaveBeenCalled()
    await userEvent.click(within(dialog).getByRole('button', { name: 'Cancel' }))
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
    expect(api.savePaperSettings).not.toHaveBeenCalled()
    expect(onChange).toHaveBeenCalledExactlyOnceWith({ ...defaults, enabled: true })
    expect(screen.getByText('Saved paper monitoring: enabled.')).toBeInTheDocument()
  })

  it('sends no PUT on cancel, then sends enabled:false only after a confirmed disable through WorkspaceApi', async () => {
    const fetcher = vi.fn(async (_path: string, init: RequestInit) => {
      const body: unknown = init.method === 'PUT' ? JSON.parse(init.body as string) : { ...defaults, enabled: true }
      return new Response(JSON.stringify(body), { status: 200 })
    })
    vi.stubGlobal('fetch', fetcher)
    const api = createWorkspaceApi('synthetic-paper-settings-token')
    render(<PaperSettings api={api} />)
    await waitFor(() => expect(screen.getByRole('switch')).toBeEnabled())
    await userEvent.click(screen.getByRole('switch'))
    await userEvent.click(screen.getByRole('button', { name: 'Save paper settings' }))
    await userEvent.click(within(await screen.findByRole('dialog')).getByRole('button', { name: 'Cancel' }))
    expect(fetcher.mock.calls.filter(([, init]) => init.method === 'PUT')).toHaveLength(0)
    await userEvent.click(screen.getByRole('button', { name: 'Save paper settings' }))
    await userEvent.click(within(await screen.findByRole('dialog')).getByRole('button', { name: 'Disable paper monitoring' }))
    expect(await screen.findByText('Saved paper monitoring: disabled.')).toBeInTheDocument()
    const writes = fetcher.mock.calls.filter(([, init]) => init.method === 'PUT')
    expect(writes).toHaveLength(1)
    expect(writes[0]?.[0]).toBe('/api/paper/settings')
    expect(JSON.parse(writes[0]![1].body as string)).toEqual(defaults)
    expect(screen.getByRole('heading', { name: 'Paper trading' })).toBeInTheDocument()
    expect(screen.getByText(/paper history stays available/)).toBeInTheDocument()
  })

  it('writes disabled settings only after confirmation, and never claims suspension before success', async () => {
    const pending = deferred<Settings>()
    const api = makeApi({ ...defaults, enabled: true })
    api.savePaperSettings.mockReturnValue(pending.promise)
    const onChange = vi.fn()
    render(<PaperSettings api={api} onChange={onChange} />)
    await waitFor(() => expect(screen.getByRole('switch')).toBeEnabled())
    await userEvent.click(screen.getByRole('switch'))
    await userEvent.click(screen.getByRole('button', { name: 'Save paper settings' }))
    await userEvent.click(within(await screen.findByRole('dialog')).getByRole('button', { name: 'Disable paper monitoring' }))
    expect(api.savePaperSettings).toHaveBeenCalledExactlyOnceWith(defaults)
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
    expect(screen.getByText('Saved paper monitoring: enabled.')).toBeInTheDocument()
    expect(onChange).toHaveBeenCalledExactlyOnceWith({ ...defaults, enabled: true })
    await act(async () => pending.resolve(defaults))
    expect(screen.getByText('Saved paper monitoring: disabled.')).toBeInTheDocument()
    expect(screen.getByText('Paper settings saved.')).toBeInTheDocument()
    expect(onChange).toHaveBeenLastCalledWith(defaults)
    expect(screen.getByText(/paper history stays available/)).toBeInTheDocument()
  })

  it('keeps saved monitoring enabled after a failed confirmed disable and requires confirmation again', async () => {
    const api = makeApi({ ...defaults, enabled: true })
    api.savePaperSettings.mockRejectedValue(new Error('Private server detail'))
    const onChange = vi.fn()
    render(<PaperSettings api={api} onChange={onChange} />)
    await waitFor(() => expect(screen.getByRole('switch')).toBeEnabled())
    await userEvent.click(screen.getByRole('switch'))
    await userEvent.click(screen.getByRole('button', { name: 'Save paper settings' }))
    await userEvent.click(within(await screen.findByRole('dialog')).getByRole('button', { name: 'Disable paper monitoring' }))
    expect(await screen.findByRole('alert')).toHaveTextContent('Paper settings could not be saved. Reload to confirm the server settings.')
    expect(screen.getByText('Saved paper monitoring: enabled.')).toBeInTheDocument()
    expect(screen.queryByText('Saved paper monitoring: disabled.')).not.toBeInTheDocument()
    expect(screen.queryByText('Paper settings saved.')).not.toBeInTheDocument()
    expect(onChange).toHaveBeenCalledExactlyOnceWith({ ...defaults, enabled: true })
    await userEvent.click(screen.getByRole('button', { name: 'Save paper settings' }))
    expect(await screen.findByRole('dialog', { name: 'Disable paper monitoring?' })).toBeInTheDocument()
    expect(api.savePaperSettings).toHaveBeenCalledTimes(1)
  })

  it('does not ask to disable when only an enabled interval changes', async () => {
    const api = makeApi({ ...defaults, enabled: true })
    render(<PaperSettings api={api} />)
    await waitFor(() => expect(screen.getByRole('spinbutton')).toBeEnabled())
    fireEvent.change(screen.getByRole('spinbutton'), { target: { value: '15' } })
    await userEvent.click(screen.getByRole('button', { name: 'Save paper settings' }))
    expect(api.savePaperSettings).toHaveBeenCalledExactlyOnceWith({ enabled: true, checkIntervalMinutes: 15 })
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
  })

  it('discards an old API confirmation without writing to the replacement API', async () => {
    const first = makeApi({ ...defaults, enabled: true })
    const second = makeApi()
    const view = render(<PaperSettings api={first} />)
    await waitFor(() => expect(screen.getByRole('switch')).toBeEnabled())
    await userEvent.click(screen.getByRole('switch'))
    await userEvent.click(screen.getByRole('button', { name: 'Save paper settings' }))
    await screen.findByRole('dialog', { name: 'Disable paper monitoring?' })
    view.rerender(<PaperSettings api={second} />)
    await waitFor(() => expect(screen.getByRole('switch')).toBeEnabled())
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
    expect(first.savePaperSettings).not.toHaveBeenCalled()
    expect(second.savePaperSettings).not.toHaveBeenCalled()
  })
})
