import { expect, it } from 'vitest'
import { price } from './format'

it.each([
  ['0.1634', '$0.1634'],
  ['0.0123', '$0.0123'],
  ['0.0127', '$0.0127'],
  ['64250.5', '$64,250.50'],
  ['0.000012345', '$0.000012345'],
  ['0.123456', '$0.12346'],
  ['12.345678', '$12.346'],
  ['1.2', '$1.20'],
  ['10', '$10.00'],
  ['0', '$0.00'],
  ['-0.1634', '-$0.1634'],
  ['000.00123456', '$0.0012346'],
  ['1.23456e-8', '$0.000000012346'],
  ['0.000000000000000000000000000123456', '$0.00000000000000000000000000012346'],
  ['1000000000000000.05', '$1,000,000,000,000,000.05'],
  ['9007199254740990.99', '$9,007,199,254,740,990.99'],
  ['79228162514264337593543950335', '$79,228,162,514,264,337,593,543,950,335.00'],
  ['-79228162514264337593543950336.25', '-$79,228,162,514,264,337,593,543,950,336.25'],
])('formats the exact price %s without float conversion', (value, expected) => {
  expect(price(value)).toBe(expected)
})

it.each([
  ['0.1634', '0.0001', '$0.1634'],
  ['0.1634', '0.0100', '$0.16'],
  ['0.1634', 0.00001, '$0.16340'],
  ['64250.5', '1', '$64,251'],
  ['64250.5', '0.25', '$64,250.50'],
  ['0.000012345', 1e-9, '$0.000012345'],
  ['1.23456789', '2.5e-7', '$1.23456789'],
  ['9007199254740990.123456789', '0.000000001', '$9,007,199,254,740,990.123456789'],
  ['0', '0.001', '$0.000'],
  ['1.25', '1000e-4', '$1.3'],
])('uses the decimals of tick %s / %s', (value, tick, expected) => {
  expect(price(value, tick)).toBe(expected)
})

it('keeps unavailable prices distinct from zero, including with a tick', () => {
  expect(price(null)).toBe('—')
  expect(price(null, '0.0001')).toBe('—')
  expect(price('0')).toBe('$0.00')
})

it.each([undefined, null, 0, -1, NaN, Infinity, '', '0.000', 'unknown'])('uses default precision without a valid tick (%s)', tick => {
  expect(price('0.0123456', tick)).toBe('$0.012346')
})
